export type TranslationKey = keyof typeof messages.en;

type TranslationValues = Record<string, string | number>;

export type I18nContextValue = {
  intlLocale: string;
  locale: AppLocale;
  localeLabel: string;
  localeOptions: Array<{ label: string; value: AppLocale }>;
  setLocale: (locale: AppLocale) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
};

const I18nContext = React.createContext<I18nContextValue | null>(null);

function isSupportedLocale(value: string | null): value is AppLocale {
  return supportedLocales.some((locale) => locale === value);
}

function interpolate(message: string | undefined, values: TranslationValues | undefined) {
  // Stored rows carry translation keys — notifications keep the key that was current when they were
  // written — so a key can outlive its catalog entry. Showing the raw key is a blemish; throwing
  // takes the whole page down, which is what deleting the budget keys did to the notification bell.
  if (message === undefined) return '';
  if (!values) {
    return message;
  }

  return Object.entries(values).reduce((current, [key, value]) => {
    return current.replaceAll(`{${key}}`, String(value));
  }, message);
}

export function I18nProvider({ children }: Readonly<{ children: React.ReactNode }>) {
  const [locale, setLocaleState] = React.useState<AppLocale>('en');

  React.useEffect(() => {
    const storedLocale = window.localStorage.getItem('tracky.locale');
    if (isSupportedLocale(storedLocale)) {
      setLocaleState(storedLocale);
    }
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem('tracky.locale', locale);
  }, [locale]);

  const value = React.useMemo<I18nContextValue>(() => {
    const t = (key: TranslationKey, values?: TranslationValues) => interpolate(messages[locale][key], values);

    return {
      intlLocale: intlLocales[locale],
      locale,
      localeLabel: localeLabels[locale],
      localeOptions: supportedLocales.map((optionLocale) => ({
        label: localeLabels[optionLocale],
        value: optionLocale,
      })),
      setLocale: setLocaleState,
      t,
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = React.useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }

  return context;
}
